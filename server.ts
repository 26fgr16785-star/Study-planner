// 3. AI Timetable Generator Endpoint
app.post('/api/gemini/timetable', async (req: Request, res: Response) => {
  try {
    const { subjects, preferredStudyTime, dailyHours, existingCommitments, examDates } = req.body;

    if (!process.env.GEMINI_API_KEY) {
      return res.status(500).json({ error: 'Gemini API key is not configured.' });
    }

    const systemPrompt = `You are an expert academic time-management counselor and scheduler for Muhammad Ali AI Smart Study Planner.
Your task is to generate a balanced, realistic, non-overlapping weekly study timetable for a student based on:
- Subjects & difficulty: ${JSON.stringify(subjects)}
- Daily study target: ${dailyHours || 3} hours per day
- Preferred study time: ${preferredStudyTime || 'Evening'}
- Upcoming exam dates: ${JSON.stringify(examDates || [])}
- Schedule constraints: Avoid overlapping sessions. Prioritize subjects with upcoming exams and higher difficulty.

Return strictly valid JSON format:
{
  "suggestedSessions": [
    {
      "subjectName": "Subject Name matching input",
      "topic": "Specific high-yield topic to study",
      "date": "YYYY-MM-DD", // Next 7 days starting from today
      "startTime": "HH:MM", // 24-hr format e.g. "17:00"
      "endTime": "HH:MM",   // 24-hr format e.g. "18:30"
      "durationMinutes": 90,
      "priority": "high" | "medium" | "low",
      "notes": "Actionable study tip or technique for this topic"
    }
  ],
  "strategyOverview": "2-3 sentences explaining why this timetable is optimized for the student's priorities."
}`;

    const todayStr = new Date().toISOString().split('T')[0];
    const response = await ai.models.generateContent({
      model: 'gemini-3.8-flash',
      contents: `Create an optimized 7-day study timetable starting today (${todayStr}) avoiding any overlaps. Target total ~${(dailyHours || 3) * 7} hours spread sensibly.`,
      config: {
        systemInstruction: systemPrompt,
        responseMimeType: 'application/json',
      },
    });

    const parsed = JSON.parse(response.text || '{}');
    res.json(parsed);
  } catch (err: unknown) {
    console.error('Timetable API error:', err);
    res.status(500).json({
      error: err instanceof Error ? err.message : 'Failed to generate timetable.',
    });
  }
});

// 4. AI Study Assistant Chatbot Endpoint
app.post('/api/gemini/chat', async (req: Request, res: Response) => {
  try {
    const { messages, studentContext } = req.body;

    if (!process.env.GEMINI_API_KEY) {
      return res.status(500).json({ error: 'Gemini API key is not configured.' });
    }

    const studentInfo = studentContext
      ? `Student Name: ${studentContext.name || 'Student'}, Education Level: ${studentContext.educationLevel || 'Undergraduate'}, Subjects: ${(studentContext.subjects || []).join(', ')}.`
      : '';

    const systemPrompt = `You are the "Muhammad Ali AI Study Assistant", a patient, brilliant, and supportive 24/7 academic tutor created by Muhammad Ali for the Muhammad Ali AI Smart Study Planner platform.
${studentInfo}

Your capabilities:
1. Break down complex concepts into simple, intuitive mental models.
2. Provide step-by-step solutions with concrete examples and clean Markdown formatting (bullet points, bold text, formulas).
3. Suggest effective revision techniques (Active Recall, Spaced Repetition, Feynman Technique).
4. Offer motivation, exam preparation tips, and time management strategies.
5. Answer questions in the language requested by the student (English by default, or Urdu/Roman Urdu if prompted in Urdu).

Always be encouraging, articulate, clear, and academically rigorous without being dry. Use markdown formatting nicely.`;

    // Convert messages array to prompt or chat structure
    const historyText = (messages || [])
      .map((m: { sender: string; content: string }) => `${m.sender === 'user' ? 'Student' : 'Assistant'}: ${m.content}`)
      .join('\n\n');

    const response = await ai.models.generateContent({
      model: 'gemini-3.8-flash',
      contents: historyText || 'Hello, I am ready to study.',
      config: {
        systemInstruction: systemPrompt,
      },
    });

    res.json({
      reply: response.text || 'I am here to assist your academic journey! What would you like to study today?',
    });
  } catch (err: unknown) {
    console.error('Chat API error:', err);
    res.status(500).json({
      error: err instanceof Error ? err.message : 'AI tutor request failed.',
    });
  }
});

