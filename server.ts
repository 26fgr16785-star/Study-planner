import express, { Request, Response } from 'express';
import { createServer as createViteServer } from 'vite';
import { GoogleGenAI } from '@google/genai';
import dotenv from 'dotenv';
import path from 'path';

dotenv.config();

const app = express();
const PORT = 3000;

app.use(express.json({ limit: '10mb' }));

// Server-side Gemini initialization following SDK guidelines
// Using gemini-3.8-flash for high quality reasoning & generation
const ai = new GoogleGenAI({
  apiKey: process.env.GEMINI_API_KEY || '',
  httpOptions: {
    headers: {
      'User-Agent': 'aistudio-build',
    },
  },
});

// Health check endpoint
app.get('/api/health', (_req: Request, res: Response) => {
  res.json({
    status: 'ok',
    appName: 'Muhammad Ali AI Smart Study Planner',
    hasApiKey: !!process.env.GEMINI_API_KEY,
  });
});

// 1. AI Quiz Generation Endpoint
app.post('/api/gemini/quiz', async (req: Request, res: Response) => {
  try {
    const { subject, topic, difficulty, numQuestions, questionType } = req.body;

    if (!process.env.GEMINI_API_KEY) {
      return res.status(500).json({
        error: 'Gemini API key is not configured on the server. Please check the Secrets panel.',
      });
    }

    const count = Math.min(Math.max(Number(numQuestions) || 5, 3), 20);
    const qType = questionType || 'mcq';
    const diff = difficulty || 'medium';

    const systemPrompt = `You are an expert university professor and exam designer for the Muhammad Ali AI Smart Study Planner.
Generate a high-quality educational quiz for a student studying "${subject}" on the topic "${topic}".
Difficulty level: ${diff}.
Number of questions: ${count}.
Question type: ${qType} (mcq = Multiple Choice with 4 options, true_false = True or False, short_answer = Short Answer question).

Output MUST be strictly valid JSON without any markdown code fence wrapping or backticks.
The JSON format must match:
{
  "questions": [
    {
      "id": "q1",
      "type": "${qType}",
      "question": "Question text here?",
      "options": ["Option A", "Option B", "Option C", "Option D"], // Only include 4 options if type is mcq, or ["True", "False"] if type is true_false. Omit for short_answer.
      "correctAnswer": "The exact correct option or reference answer text",
      "explanation": "Clear educational explanation explaining why this answer is correct and key concepts."
    }
  ]
}`;

    const response = await ai.models.generateContent({
      model: 'gemini-3.8-flash',
      contents: `Generate ${count} questions for subject: ${subject}, topic: ${topic}, difficulty: ${diff}, format: ${qType}. Ensure all facts and solutions are strictly correct.`,
      config: {
        systemInstruction: systemPrompt,
        responseMimeType: 'application/json',
      },
    });

    const rawText = response.text || '{}';
    let parsedData;
    try {
      parsedData = JSON.parse(rawText);
    } catch {
      // Clean fallback if minor token artifact occurs
      const cleaned = rawText.replace(/```json/g, '').replace(/```/g, '').trim();
      parsedData = JSON.parse(cleaned);
    }

    if (!parsedData.questions || !Array.isArray(parsedData.questions)) {
      throw new Error('Invalid quiz response structure generated by AI');
    }

    res.json(parsedData);
  } catch (err: unknown) {
    console.error('Quiz Generation API error:', err);
    res.status(500).json({
      error: err instanceof Error ? err.message : 'Failed to generate quiz with AI.',
    });
  }
});

